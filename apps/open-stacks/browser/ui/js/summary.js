// AI summaries: after 5 s on an item (or `a`), the server asks Claude for a
// structured summary of the text the reader extracts here, with page markers.
import { $, h, on, emit, registerSection, registerKey, store } from './util.js';
import { items, LANES } from './corpus.js';
import { state, current } from './state.js';
import { openDoc, isFlow, peekDoc } from './docs.js';
import { startOf } from './prefetch.js';
import { goPage } from './nav.js';
import { paintScrub } from './feed.js';

export const summaries = new Map(); // id -> summary object
let dwellTimer = null;

registerSection({
  id: 'summary', title: 'Summary', order: 20,
  render(it, i) {
    const box = h('div', { id: 'sum' });
    const presum = h('label', { className: 'toggle' }, h('input', { type: 'checkbox', checked: state.presum, onchange: (e) => { state.presum = e.target.checked; store.set('presum', state.presum); } }), 'also summarize the next two items');
    clearTimeout(dwellTimer);
    queueMicrotask(() => paintSummary(it));
    if (!summaries.has(it.id)) {
      fetch('/summary?id=' + encodeURIComponent(it.id)).then((r) => r.json()).then((s) => {
        if (s) { setSummary(it, s); return; }
        if (state.panelItem !== it.id) return;
        paintSummary(it, 'countdown');
        dwellTimer = setTimeout(() => { if (state.panelItem === it.id) summarizeItem(i, true); }, 5000);
      }).catch(() => {});
    }
    return h('div', {}, box, presum);
  },
});

function setSummary(it, s) {
  summaries.set(it.id, s);
  if (s && !s.error) state.marks.set(it.id, (s.key_points || []).map((k) => k.page).filter(Boolean));
  emit('summary:updated', { id: it.id, summary: s });
  if (state.panelItem === it.id) {
    paintSummary(it);
    const i = current();
    const sh = state.shown || 1;
    if (!isFlow(it)) paintScrub(i, startOf(i), sh);
  }
}

export function paintSummary(it, mode) {
  const box = $('#sum'); if (!box) return;
  const s = summaries.get(it.id);
  if (s && !s.error) {
    box.replaceChildren(h('div', { className: 'sum' },
      h('div', { className: 'verdict' }, h('span', { className: 'pill ' + s.verdict, textContent: s.verdict }), `${s.minutes} min`),
      h('div', { className: 'care', textContent: s.why_care }),
      h('div', { className: 'gist', textContent: s.gist }),
      h('ul', {}, ...(s.key_points || []).map((kp) => h('li', {}, kp.point, kp.page ? h('span', { className: 'pl', textContent: 'p. ' + kp.page, onclick: () => goPage(kp.page - 1) }) : null))),
      s.this_spread ? h('div', { className: 'spread', textContent: 'On the pages first shown: ' + s.this_spread }) : null,
      h('div', { className: 'ai-note', textContent: `AI-generated by ${s.model} · may be wrong` })));
    return;
  }
  if (s?.error) { box.replaceChildren(h('div', { className: 'sum-state', textContent: s.error })); return; }
  if (mode === 'working') box.replaceChildren(h('div', { className: 'sum-state working' }, 'Summarizing…', h('span', { className: 'bar' })));
  else if (state.status.summariesEnabled === false) box.replaceChildren(h('div', { className: 'sum-state', textContent: 'Summaries are off. Start the server with ANTHROPIC_API_KEY set (and run npm install once).' }));
  else if (mode === 'countdown') box.replaceChildren(h('div', { className: 'sum-state' }, 'Summary in 5 s if you stay (a: now)', h('span', { className: 'bar' })));
  else box.replaceChildren();
}

/** Text with [p. N] markers, around where the reader is, for the summarizer. */
export async function extractText(it, s) {
  const d = await openDoc(it);
  const parts = [];
  if (d.pdf) {
    const pages = new Set([...Array(Math.min(d.n, 10)).keys(), ...[0, 1, 2].map((j) => s + j).filter((k) => k < d.n)]);
    for (const k of [...pages].sort((a, b) => a - b)) {
      const tc = await (await d.pdf.getPage(k + 1)).getTextContent();
      parts.push(`[p. ${k + 1}] ` + tc.items.map((x) => x.str).join(' '));
      if (parts.join('').length > 70000) break;
    }
  } else if (it.kind === 'scan') {
    const r = await fetch('/proxy?u=' + encodeURIComponent(`https://archive.org/download/${it.ia}/${it.ia}_djvu.txt`));
    if (!r.ok) throw new Error('No OCR text for this scan');
    const t = await r.text();
    const at = Math.floor((s / Math.max(1, it.n)) * t.length);
    parts.push('[opening pages]\n' + t.slice(0, 15000), `\n[around p. ${s + 1}]\n` + t.slice(Math.max(15000, at - 8000), at + 25000));
  } else {
    d.texts.forEach((x, k) => parts.push(`[p. ${k + 1}] ${x}`));
  }
  return parts.join('\n').slice(0, 85000);
}
export async function summarizeItem(i, visible) {
  const it = items[i];
  if (summaries.has(it.id) && !summaries.get(it.id).error) return;
  if (visible) paintSummary(it, 'working');
  const s = isFlow(it) ? 0 : startOf(i);
  let out;
  try {
    const text = await extractText(it, s);
    const r = await fetch('/summarize', { method: 'POST', body: JSON.stringify({ id: it.id, title: it.t, authors: it.a, year: it.y, lane: LANES[it.lane], laneId: it.lane, kind: it.kind, text, spread: `${s + 1}-${s + state.per}` }) });
    const j = await r.json();
    out = j.error ? { error: j.code === 'no_key' || j.code === 'no_sdk' ? j.error : 'Summary failed: ' + j.error } : j;
  } catch (e) { out = { error: 'Summary failed: ' + e.message }; }
  setSummary(it, out);
  if (visible && state.presum && !out.error) for (const ii of state.order.slice(state.pos + 1, state.pos + 3)) summarizeItem(ii, false);
}
registerKey('a', () => summarizeItem(current(), true), { help: ['a', 'summarize now (otherwise after 5 s)'], order: 31 });
