HERE = os.path.dirname(os.path.abspath(__file__))
log2 = math.log2

# ---------------------------------------------------------------- the process
PRIOR = 0.5                      # P(H)
# Evidence: four grades, strongly-against .. strongly-for.
P_E_GIVEN_H = [0.02, 0.08, 0.30, 0.60]
P_E_GIVEN_NOT_H = P_E_GIVEN_H[::-1]
A_STRENGTH = 0.10                # evaluator misreads strength (strong <-> weak)
B_SIGN = 0.25                    # evaluator slips sign on weak evidence
R_SKIP = 0.30                    # consumer half-reads: absorbs nothing


def evaluator(e):
    a, b = A_STRENGTH, B_SIGN
    return {0: {0: 1 - a, 1: a},
            1: {1: 1 - a - b, 0: a, 2: b},
            2: {2: 1 - a - b, 3: a, 1: b},
            3: {3: 1 - a, 2: a}}[e]


def push(joint, kernel):
    out = {}
    for (h, x), p in joint.items():
        for y, k in kernel(x).items():
            out[(h, y)] = out.get((h, y), 0.0) + p * k
    return out


def mi(joint):
    ph, py = {}, {}
    for (h, y), p in joint.items():
        ph[h] = ph.get(h, 0) + p
        py[y] = py.get(y, 0) + p
    return sum(p * log2(p / (ph[h] * py[y])) for (h, y), p in joint.items() if p > 0)


def build(captured=False):
    jE = {}
    for h, pe in ((1, P_E_GIVEN_H), (0, P_E_GIVEN_NOT_H)):
        for e, p in enumerate(pe):
            jE[(h, e)] = (PRIOR if h else 1 - PRIOR) * p
    jJ = push(jE, evaluator)                                  # evaluator's verdict
    if captured:
        jJ = push(jJ, lambda j: {3 - j: 1.0})                 # optimizer inverts it
    jR = push(jJ, lambda j: {int(j >= 2): 1.0})               # rubric: pass / fail
    jI = push(jR, lambda r: {r: 1 - R_SKIP, '?': R_SKIP})     # consumer reads or skips
    return {'evidence': jE, 'verdict': jJ, 'report': jR, 'interp': jI}


honest = build(False)
captured = build(True)
I = {k: mi(v) for k, v in honest.items()}
Ic = {k: mi(v) for k, v in captured.items()}

# Data-processing inequality, honest and captured.
for d in (I, Ic):
    assert d['evidence'] >= d['verdict'] >= d['report'] >= d['interp'] > 0
# Inversion is a bijection: the captured chain carries exactly the same bits.
for k in I:
    assert abs(I[k] - Ic[k]) < 1e-12, k

L_eval = 1 - I['verdict'] / I['evidence']
L_cod = 1 - I['report'] / I['verdict']
L_interp = 1 - I['interp'] / I['report']
# The page's product formula telescopes exactly when losses are MI ratios.
assert abs(I['evidence'] * (1 - L_cod) * (1 - L_eval) * (1 - L_interp) - I['interp']) < 1e-12


def likelihoods(joint):
    """P(signal | H), P(signal | not H) from a joint."""
    lh, ln = {}, {}
    for (h, y), p in joint.items():
        (lh if h else ln)[y] = (lh if h else ln).get(y, 0) + p / (PRIOR if h else 1 - PRIOR)
    return lh, ln


def judge_value(truth_joint, believed_joint):
    """Expected log-score gain (bits) of a judge who updates with the likelihood
    ratio of `believed_joint` while signals are generated by `truth_joint`."""
    lh, ln = likelihoods(believed_joint)
    gain = 0.0
    prior_odds = PRIOR / (1 - PRIOR)
    for (h, y), p in truth_joint.items():
        odds = prior_odds * lh[y] / ln[y]          # posterior odds = prior odds x LR
        post = odds / (1 + odds)
        q_true = post if h else 1 - post
        q_prior = PRIOR if h else 1 - PRIOR
        gain += p * (log2(q_true) - log2(q_prior))
    return gain


V_honest = judge_value(honest['interp'], honest['interp'])
V_stale = judge_value(captured['interp'], honest['interp'])       # keeps pre-capture LR
V_inverted = judge_value(captured['interp'], captured['interp'])  # knows, reads it inverted
assert abs(V_honest - I['interp']) < 1e-12      # expected log-score gain = MI
assert abs(V_inverted - I['interp']) < 1e-12    # "a ratio known to sit below 1 is still informative"
assert V_stale < 0                              # misleading: negative value

# Section 5 identity on the same process (forecast q = P(H), source X = interpretation).
lh, ln = likelihoods(honest['interp'])
q = PRIOR
move = resolved = mean_qx = 0.0
for y in lh:
    px = q * lh[y] + (1 - q) * ln[y]
    qx = q * lh[y] / px
    mean_qx += px * qx
    move += px * (qx - q) ** 2
    resolved += px * qx * (1 - qx)
resolved = q * (1 - q) - resolved
assert abs(mean_qx - q) < 1e-12                 # conservation of expected evidence
assert abs(move - resolved) < 1e-12             # expected movement = uncertainty resolved

