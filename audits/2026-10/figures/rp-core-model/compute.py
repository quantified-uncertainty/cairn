def band_path(axis0, pts, tip, sign, vertical=False):
    """Sankey-style band hanging off the LR = 1 line. pts: [(pos, width)]; sign +1/-1."""
    def P(along, across):
        return f'{f(across)} {f(along)}' if vertical else f'{f(along)} {f(across)}'
    first, last = pts[0][0], pts[-1][0]
    hl = pts[-1][1]
    edge = ' L'.join(P(a, axis0 - sign * h) for a, h in pts)
    return f'M{P(first, axis0)} L{edge} L{P(tip, axis0 - sign * hl / 2)} L{P(last, axis0)} Z'


