def rich(s, size):
    """Tiny markup -> tspans. *x* italic, _{...} subscript (may contain *x*)."""
    out = []
    shift = 0
    sub = round(size * 0.78)

    def emit(text, italic=False, is_sub=False):
        nonlocal shift
        want = SUB_DY.get(size, 4) if is_sub else 0
        attrs = []
        if want != shift:
            attrs.append(f'dy="{want - shift}"')
            shift = want
        if italic:
            attrs.append('font-style="italic"')
        if is_sub:
            attrs.append(f'font-size="{sub}"')
        a = (' ' + ' '.join(attrs)) if attrs else ''
        out.append(f'<tspan{a}>{escape(text)}</tspan>')

    pos = 0
    for m in re.finditer(r'_\{((?:[^{}])*)\}|\*([^*]+)\*', s):
        if m.start() > pos:
            emit(s[pos:m.start()])
        if m.group(1) is not None:
            for part in re.split(r'(\*[^*]+\*)', m.group(1)):
                if part:
                    if part.startswith('*'):
                        emit(part[1:-1], italic=True, is_sub=True)
                    else:
                        emit(part, is_sub=True)
        else:
            emit(m.group(2), italic=True)
        pos = m.end()
    if pos < len(s):
        emit(s[pos:])
    if shift:
        out.append(f'<tspan dy="{-shift}"></tspan>')
    return ''.join(out)


def text(x, y, s, cls='t', anchor='start', size=15):
    a = '' if anchor == 'start' else f' text-anchor="{anchor}"'
    return f'<text x="{x:g}" y="{y:g}" class="{cls}"{a}>{rich(s, size)}</text>'


def f(v):
    return f'{v:.1f}'.rstrip('0').rstrip('.')


def arrowhead(x, y, dx, dy, cls, size=7):
    """Open-angle arrowhead at (x, y) pointing along (dx, dy)."""
    n = math.hypot(dx, dy)
    ux, uy = dx / n, dy / n
    px, py = -uy, ux
    a = (x - ux * size + px * size * 0.55, y - uy * size + py * size * 0.55)
    b = (x - ux * size - px * size * 0.55, y - uy * size - py * size * 0.55)
    return f'<path d="M{f(a[0])} {f(a[1])} L{f(x)} {f(y)} L{f(b[0])} {f(b[1])}" class="{cls}"/>'


