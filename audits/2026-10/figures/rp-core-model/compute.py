#!/usr/bin/env python3
"""rp-core-model: the loss pipeline, drawn to scale for one illustrative process.

Everything the figure draws is computed here from the page's own formulas
(concepts/core-model.md):

  * the exact skeleton (section 2): a Markov chain World -> Evidence -> Report
    -> Interpretation, whose mutual informations I(World; stage) must be
    non-increasing (data-processing inequality). Band widths are these values.
  * the heuristic (section 2): V_delivered = V_source (1-L_cod)(1-L_eval)(1-L_interp).
    Each L is read off as a mutual-information ratio, so the product telescopes
    to I(World; Interpretation) / I(World; Evidence) exactly.
  * "bias is not attenuation" (section 2, failure mode 3) and the captured
    process (sections 1 and 4): an evaluator that inverts its verdicts keeps
    every bit (I is unchanged by a bijection) but a judge still using the
    pre-capture likelihood ratio is moved away from the truth: negative value.
  * epistemic weight (section 1): posterior odds = prior odds x LR.
  * pricing (section 5): E[(q_X - q)^2] = q(1-q) - E[q_X(1-q_X)], checked on
    the same process.

The process parameters are illustrative (the page gives no numbers); only the
shape claims are general, and each is asserted below.

Run: python3 compute.py   -> writes data.json, figure.html, index.html
"""
